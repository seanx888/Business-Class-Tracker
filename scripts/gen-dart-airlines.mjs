// Generates apps/mobile/lib/domain/airlines.g.dart from web/core/airlines.js so the Flutter app
// and the PWA/scanner share ONE airline table (alliance changes are edited in a single place).
//   node scripts/gen-dart-airlines.mjs           → rewrite the Dart file
//   node scripts/gen-dart-airlines.mjs --check   → exit 1 when the committed file is stale (used by npm test)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { AIRLINES, LCC_CARRIERS, BLOCKED_CARRIERS } from '../web/core/airlines.js';

export const OUT = fileURLToPath(new URL('../apps/mobile/lib/domain/airlines.g.dart', import.meta.url));

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

export function render() {
  const rows = Object.entries(AIRLINES)
    .map(([code, a]) => `  ${q(code)}: (en: ${q(a.en)}, zh: ${q(a.zh)}, alliance: ${q(a.alliance)}, country: ${q(a.country)}, url: ${q(a.url)}),`)
    .join('\n');
  const lcc = [...LCC_CARRIERS].map((c) => q(c)).join(', ');
  const blocked = Object.entries(BLOCKED_CARRIERS).map(([c, n]) => `${q(c)}: ${q(n)}`).join(', ');
  return `// GENERATED by scripts/gen-dart-airlines.mjs from web/core/airlines.js — do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

/// code → (English name, 中文名, alliance key SKYTEAM|STAR|ONEWORLD|NONE, home country, website)
const airlineTable = <String, ({String en, String zh, String alliance, String country, String url})>{
${rows}
};

/// Low-cost carriers (their "business class" is often just a flat seat).
const lccCarriers = <String>{${lcc}};

/// Carriers based in mainland China / Hong Kong / Macau (excluded from fare search; still recognised as airline codes).
const blockedCarrierNames = <String, String>{${blocked}};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render();
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8');
    if (cur !== next) {
      console.error('airlines.g.dart is stale — run: node scripts/gen-dart-airlines.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
