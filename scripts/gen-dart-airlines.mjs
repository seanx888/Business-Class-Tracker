// Generates apps/mobile/lib/domain/airlines.g.dart (from web/core/airlines.js) and programs.g.dart (from
// web/core/programs.js) so the Flutter app, the PWA and the scanner share ONE airline / loyalty-program table
// (alliance changes are edited in a single place, and a wallet backup exported from the PWA imports in full).
//   node scripts/gen-dart-airlines.mjs           → rewrite the Dart file
//   node scripts/gen-dart-airlines.mjs --check   → exit 1 when the committed file is stale (used by npm test)
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { AIRLINES, LCC_CARRIERS, BLOCKED_CARRIERS } from '../web/core/airlines.js';
import { PROGRAMS } from '../web/core/programs.js';

export const OUT = fileURLToPath(new URL('../apps/mobile/lib/domain/airlines.g.dart', import.meta.url));
// IATA → ISO country (OurAirports); the app bundles a copy for its Passport stats.
export const AIRPORTS_SRC = fileURLToPath(new URL('../config/airport-countries.json', import.meta.url));
export const AIRPORTS_OUT = fileURLToPath(new URL('../apps/mobile/assets/airport-countries.json', import.meta.url));
// IATA → [lat, lon, city]; distance of hand-entered flights, route map, connection checks.
export const GEO_SRC = fileURLToPath(new URL('../config/airport-geo.json', import.meta.url));
export const GEO_OUT = fileURLToPath(new URL('../apps/mobile/assets/airport-geo.json', import.meta.url));
export const ASSET_COPIES = [[AIRPORTS_SRC, AIRPORTS_OUT], [GEO_SRC, GEO_OUT]];
export const OUT_PROGRAMS = fileURLToPath(new URL('../apps/mobile/lib/domain/programs.g.dart', import.meta.url));

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

export function render() {
  const rows = Object.entries(AIRLINES)
    .map(([code, a]) => `  ${q(code)}: (en: ${q(a.en)}, zh: ${q(a.zh)}, alliance: ${q(a.alliance)}, country: ${q(a.country)}, url: ${q(a.url)}),`)
    .join('\n');
  const lcc = [...LCC_CARRIERS].map((c) => q(c)).join(', ');
  const blocked = Object.entries(BLOCKED_CARRIERS).map(([c, n]) => `${q(c)}: ${q(n)}`).join(', ');
  return `// GENERATED by scripts/gen-dart-airlines.mjs from web/core/airlines.js — do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

/// code → (English name, 中文名, alliance key SKYTEAM|STAR|ONEWORLD|NONE, home country, website)
const airlineTable = <String, ({String en, String zh, String alliance, String country, String url})>{
${rows}
};

/// Low-cost carriers (their "business class" is often just a flat seat).
const lccCarriers = <String>{${lcc}};

/// Carriers based in mainland China / Hong Kong / Macau (excluded from fare search; still recognised as airline codes).
const blockedCarrierNames = <String, String>{${blocked}};
`;
}

export function renderPrograms() {
  const rows = Object.entries(PROGRAMS)
    .map(([key, p]) => `  ${q(key)}: (carrier: ${q(p.carrier ?? '')}, en: ${q(p.en)}, zh: ${q(p.zh)}, ko: ${q(p.ko)}, tiers: [${p.tiers.map(q).join(', ')}]),`)
    .join('\n');
  return `// GENERATED by scripts/gen-dart-airlines.mjs from web/core/programs.js — do not edit by hand.

/// key → (marketing carrier — empty for hotel / car-rental programs, English name, 中文, 한국어, suggested tier names) — same keys as the PWA wallet backup.
const programTable = <String, ({String carrier, String en, String zh, String ko, List<String> tiers})>{
${rows}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outputs = [[OUT, render()], [OUT_PROGRAMS, renderPrograms()]];
  if (process.argv.includes('--check')) {
    for (const [file, next] of outputs) {
      if (readFileSync(file, 'utf8') !== next) {
        console.error(`${file} is stale — run: node scripts/gen-dart-airlines.mjs`);
        process.exit(1);
      }
    }
    for (const [src, out] of ASSET_COPIES) {
      if (!readFileSync(src).equals(readFileSync(out))) {
        console.error(`${out} is stale — run: node scripts/gen-dart-airlines.mjs`);
        process.exit(1);
      }
    }
  } else {
    for (const [file, next] of outputs) {
      writeFileSync(file, next);
      console.log(`wrote ${file}`);
    }
    for (const [src, out] of ASSET_COPIES) {
      copyFileSync(src, out);
      console.log(`copied ${out}`);
    }
  }
}
